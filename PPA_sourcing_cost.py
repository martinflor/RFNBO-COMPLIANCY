"""Standalone PPA sourcing cost sweep.

This script reuses the existing ENTSOE CSV loading helpers from
RFNBO_orchestrator.py and the PPA production helper in rfnbo_calculations.py.

It sweeps PPA-to-electrolyser ratios and day-ahead market (DAM) premiums to estimate
the sourcing cost of a PPA referenced to the DAM. 

### Cost Calculation Logic (Financial PPA Settlement)
The script models the PPA purely financially. All electrolyser consumption is assumed 
to be purchased from the day-ahead market, and the PPA premium is settled separately:

    Baseline Grid Cost = Total Electrolyser Consumption * DAM price
    Incremental PPA Cost = Matched PPA Energy * Margin
    Total Cost = Baseline Grid Cost + Incremental PPA Cost

Note on "Residual Grid Energy": 
While the script calculates a `grid_energy_mwh` (residual grid) metric, this is strictly 
used for volume reporting in the summary CSV (to show how much physical energy was not 
matched by the PPA). It is NOT used in the cost calculations, because the baseline 
DAM price is already applied to 100% of the electrolyser's consumption.

### Expected Inputs
* **Market Data:** ENTSO-E generation, prices, and installed capacity CSVs (loaded from the specified `--data-dir`).
* **Electrolyser Capacity:** Required baseline load defined via `--electrolyser-mw`.
* **RFNBO Sweep Data:** A pre-calculated CSV mapping PPA ratios to RFNBO compliance fractions (generated by `rfnbo_ratio_sweep_cli.py` or calculated on-the-fly).

### Expected Outputs
1.  **Detailed CSV (`*_ppa_sourcing_cost_detail.csv`):** Row-by-row temporal calculations of energy and cost for every timestep and scenario.
2.  **Summary CSV (`*_ppa_sourcing_cost_summary.csv`):** Compact aggregations showing total energy volumes, average costs (€/MWh), PPA shares, and overall RFNBO compliance per swept scenario.
3.  **Interactive Plot (`*_ppa_sourcing_cost_summary_plot.html`):** An HTML scatter plot showing the aggregated cost against the PPA-to-electrolyser ratio, categorized by technology type and margin.

### Example CLI Usage

**1. Basic Run (Defaults for Belgium):**
Runs the sweep using default ratios (0.0 to 2.0) and margins (1 to 5 EUR/MWh) for a 100 MW electrolyser, automatically opening the HTML plot when finished.
> python ppa_sweep.py --country Belgium --electrolyser-mw 100 --open-html

**2. Targeted Scenario Sweep:**
Evaluates specific PPA-to-electrolyser ratios and margins for only Solar and Wind Onshore, using hourly temporal correlation.
> python ppa_sweep.py \
    --country Germany \
    --electrolyser-mw 50 \
    --ratios 0.5 1.0 1.5 \
    --margins 2.0 4.0 \
    --technologies "Solar" "Wind Onshore" \
    --temporal-correlation hourly

**3. Specific Date Range and File Paths:**
Runs the sweep for a specific year, explicitly passing the required pre-computed RFNBO sweep CSV instead of searching the default outputs directory.
> python ppa_sweep.py \
    --country France \
    --electrolyser-mw 200 \
    --start 2023-01-01 --end 2023-12-31 \
    --rfnbo-file custom_folder/France_hourly_ratio_sweep.csv
"""

