def main() -> None:
    parser = _build_parser()
    args = parser.parse_args()

    if args.solar_fraction is not None and not (0.0 <= args.solar_fraction <= 1.0):
        raise ValueError("--solar-fraction must be between 0 and 1")

    prices_df, generation_df, capacity_df = _load_input_data(args)
    renewable_share = calculate_renewable_share(generation_df)
    rfnbo_sweep_df = _load_rfnbo_sweep_data(args)
    ppa_series_df = _load_ppa_series(args)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    detail_frames: list[pd.DataFrame] = []
    summary_frames: list[pd.DataFrame] = []
    for technology in args.technologies:
        solar_fraction = args.solar_fraction
        if solar_fraction is None and "+" in technology:
            solar_fraction = 0.5

        for ratio in args.ratios:
            base_detail_df = _scenario_rows(
                prices_df=prices_df,
                generation_df=generation_df,
                capacity_df=capacity_df,
                rfnbo_sweep_df=rfnbo_sweep_df,
                recalc_missing_rfnbo=args.rfnbo_recalc_missing,
                ppa_series_df=ppa_series_df,
                country=args.country,
                electrolyser_mw=args.electrolyser_mw,
                ratio=ratio,
                technology=technology,
                mode=args.temporal_correlation,
                solar_fraction=solar_fraction,
            )

            if base_detail_df.empty:
                continue

            for margin in args.margins:
                print(f"Running {technology} ratio {ratio:g} margin {margin:g} €/MWh...")
                detail_df = _apply_cost_columns(base_detail_df, margin)
                detail_frames.append(detail_df)
                summary_frames.append(_summarise_scenario(detail_df))

    if not detail_frames:
        raise ValueError("PPA sourcing cost sweep produced no rows.")

    detail_out = Path(args.output_file) if args.output_file else output_dir / f"{args.country}_{args.temporal_correlation}_ppa_sourcing_cost_detail.csv"
    summary_out = Path(args.summary_file) if args.summary_file else output_dir / f"{args.country}_{args.temporal_correlation}_ppa_sourcing_cost_summary.csv"
    plot_out = Path(args.plot_file) if args.plot_file else output_dir / f"{args.country}_{args.temporal_correlation}_ppa_sourcing_cost.html"

    detail_df = pd.concat(detail_frames, ignore_index=True)
    summary_df = pd.concat(summary_frames, ignore_index=True)
    detail_df.to_csv(detail_out, index=False)
    summary_df.to_csv(summary_out, index=False)

    plot_out = Path(args.plot_file) if args.plot_file else output_dir / f"{args.country}_{args.temporal_correlation}_ppa_sourcing_cost_summary_plot.html"
    _build_summary_plot(summary_df, args.country, args.temporal_correlation, plot_out)

    print(detail_out)
    print(summary_out)
    print(plot_out)

    if args.open_html:
        webbrowser.open(plot_out.resolve().as_uri())


if __name__ == "__main__":
    main()